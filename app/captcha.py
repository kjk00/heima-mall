def dark_color():
    return tuple(secrets.randbelow(100) + 20 for _ in range(3))


def png_bytes(width, height, pixels):
    raw = b''.join(b'\x00' + bytes(pixels[row * width * 3:(row + 1) * width * 3]) for row in range(height))

    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))

    return (b'\x89PNG\r\n\x1a\n'
            + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 2, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(raw, 6)) + chunk(b'IEND', b''))


def render(code):
    background = tuple(secrets.randbelow(16) + 240 for _ in range(3))
    pixels = bytearray(background * (WIDTH * HEIGHT))

    def put(x, y, color):
        if 0 <= x < WIDTH and 0 <= y < HEIGHT:
            offset = (y * WIDTH + x) * 3
            pixels[offset:offset + 3] = bytes(color)

    for index, character in enumerate(code):
        color = dark_color()
        left = MARGIN + index * (GLYPH_WIDTH * SCALE + GAP)
        top = MARGIN + secrets.randbelow(JITTER + 1)
        for row, bits in enumerate(FONT[character]):
            for column in range(GLYPH_WIDTH):
                if bits & (1 << (GLYPH_WIDTH - 1 - column)):
                    for dy in range(SCALE):
                        for dx in range(SCALE):
                            put(left + column * SCALE + dx, top + row * SCALE + dy, color)
    for _ in range(3):
        color = dark_color()
        x0, y0 = secrets.randbelow(WIDTH), secrets.randbelow(HEIGHT)
        x1, y1 = secrets.randbelow(WIDTH), secrets.randbelow(HEIGHT)
        steps = max(abs(x1 - x0), abs(y1 - y0), 1)
        for step in range(steps + 1):
            put(x0 + (x1 - x0) * step // steps, y0 + (y1 - y0) * step // steps, color)
    for _ in range(160):
        put(secrets.randbelow(WIDTH), secrets.randbelow(HEIGHT),
            tuple(secrets.randbelow(160) + 60 for _ in range(3)))
    return png_bytes(WIDTH, HEIGHT, pixels)


def generate():
    code = ''.join(secrets.choice(ALPHABET) for _ in range(LENGTH))
    image = 'data:image/png;base64,' + base64.b64encode(render(code)).decode()
    return code, image